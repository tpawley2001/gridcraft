#[test]
fn poi_number_format_approx_tests() {
    let wrong: Vec<String> = CASES
        .iter()
        .filter_map(|&(code, v, want)| {
            let got = text_function(&Value::Number(v), code, DateSystem::D1900);
            let ok = if want == "#VALUE!" { got == Err(CellError::Value) } else { got.as_deref() == Ok(want) };
            (!ok).then(|| format!("TEXT({v}, {code:?}) = {got:?}, Excel {want:?}"))
        })
        .collect();
    assert!(wrong.is_empty(), "{} of {} cases differ:\n{}", wrong.len(), CASES.len(), wrong.join("\n"));
}
