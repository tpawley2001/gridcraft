#[test]
fn text_general_matches_excel() {
    let mut bad = Vec::new();
    for &(v, want) in CASES {
        let got = text_function(&Value::Number(v), "General", DateSystem::D1900);
        if got.as_deref() != Ok(want) {
            bad.push(format!("TEXT({v:e}, \"General\"): got {got:?}, Excel {want:?}"));
        }
    }
    assert!(bad.is_empty(), "{} of {} rows differ:\n{}", bad.len(), CASES.len(), bad.join("\n"));
}
