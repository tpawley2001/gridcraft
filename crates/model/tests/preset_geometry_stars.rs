//! Six- to thirty-two-point stars (ECMA-376 Part 1 presetShapeDefinitions `star6`, `star7`, `star8`, `star10`,
//! `star12`, `star16`, `star24`, `star32`). Expected vertices were computed from the preset guides in floating point,
//! rounded, then pinned into the shape box (star7/star10 overshoot it by a few units, as star5 does). Polygons are
//! compared up to their starting vertex and direction; each coordinate may differ by two units (integer guides truncate).
use gridcraft_model::{GeometryPath, PathCommand, PathShade, ShapeGeometry, preset_paths};

fn geom(preset: &str, adjust: &[(&str, &str)]) -> ShapeGeometry {
    ShapeGeometry { preset: preset.into(), adjust: adjust.iter().map(|(n, f)| (n.to_string(), f.to_string())).collect(), paths: vec![] }
}

/// The one closed path's vertices.
fn polygon(paths: &[GeometryPath]) -> Vec<(i64, i64)> {
    assert_eq!(paths.len(), 1, "one path");
    let cmds = &paths[0].commands;
    assert_eq!(cmds.last(), Some(&PathCommand::Close), "path ends with Close");
    assert!(matches!(cmds.first(), Some(PathCommand::MoveTo(..))), "path starts with MoveTo");
    cmds.iter()
        .filter_map(|c| match *c {
            PathCommand::MoveTo(x, y) | PathCommand::LineTo(x, y) => Some((x, y)),
            PathCommand::Close => None,
            ref other => panic!("unexpected command {other:?}"),
        })
        .collect()
}

fn near(a: (i64, i64), b: (i64, i64)) -> bool {
    (a.0 - b.0).abs() <= 2 && (a.1 - b.1).abs() <= 2
}

fn same_cycle(actual: &[(i64, i64)], expected: &[(i64, i64)]) -> bool {
    let n = expected.len();
    if actual.len() != n {
        return false;
    }
    let rev: Vec<_> = expected.iter().rev().copied().collect();
    [expected.to_vec(), rev].iter().any(|e| (0..n).any(|k| (0..n).all(|i| near(actual[(i + k) % n], e[i]))))
}

fn check(preset: &str, adjust: &[(&str, &str)], w: i64, h: i64, expected: &[(i64, i64)]) {
    let paths = preset_paths(&geom(preset, adjust), w, h).unwrap_or_else(|| panic!("{preset} has an outline"));
    let p = &paths[0];
    assert!(p.fill && p.stroke, "{preset}: filled and stroked");
    assert_eq!(p.shade, PathShade::Norm, "{preset}: plain fill");
    assert_eq!((p.w, p.h), (w, h), "{preset}: path box is the shape box");
    let actual = polygon(&paths);
    assert!(same_cycle(&actual, expected), "{preset} {adjust:?} in {w}x{h}:\n actual   {actual:?}\n expected {expected:?}");
}

