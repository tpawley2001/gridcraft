#[test]
fn star_adjustments_are_pinned_to_0_and_50000() {
    for preset in STARS {
        for (outside, bound) in [("-9223372036854775808", "0"), ("-5", "0"), ("9223372036854775807", "50000"), ("70000", "50000")] {
            let actual = preset_paths(&geom(preset, &[("adj", &format!("val {outside}"))]), 1000, 700).expect("supported preset");
            let expected = preset_paths(&geom(preset, &[("adj", &format!("val {bound}"))]), 1000, 700).expect("supported preset");
            assert_eq!(actual, expected, "{preset}: adj={outside}");
        }
    }
}

#[test]
fn star_vertices_stay_in_hostile_boxes() {
    for preset in STARS {
        for (w, h) in [(1, 1), (7, 3), (1, i64::MAX), (i64::MAX, 1), (i64::MAX, i64::MAX)] {
            let paths = preset_paths(&geom(preset, &[]), w, h).unwrap_or_else(|| panic!("{preset} has an outline"));
            for (x, y) in polygon(&paths) {
                assert!((0..=w).contains(&x) && (0..=h).contains(&y), "{preset} in {w}x{h}: ({x}, {y}) outside the box");
            }
        }
    }
}

#[test]
fn star_with_empty_box_has_no_outline() {
    for preset in STARS {
        assert_eq!(preset_paths(&geom(preset, &[]), 0, 100), None, "{preset}");
        assert_eq!(preset_paths(&geom(preset, &[]), 100, -1), None, "{preset}");
    }
}
