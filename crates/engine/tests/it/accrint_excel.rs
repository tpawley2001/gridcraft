#[test]
fn accrint_matches_excel() {
    let mut s = Session::new();
    s.new_workbook();
    for (i, (f, _)) in CASES.iter().enumerate() {
        s.execute("cell.set", json!({"cell": format!("A{}", i + 1), "input": format!("={f}")})).unwrap();
    }
    let sheet = s.doc().unwrap().wb.sheet(0).unwrap();
    let mut wrong = Vec::new();
    for (i, (f, want)) in CASES.iter().enumerate() {
        let got = sheet.value(CellRef::parse(&format!("A{}", i + 1)).unwrap());
        let ok = matches!(got, Value::Number(n) if (n - want).abs() <= 1e-9 * want.abs().max(1.0));
        if !ok {
            wrong.push(format!("{f}: Excel {want}, got {got:?}"));
        }
    }
    assert!(wrong.is_empty(), "{} of {} differ from Excel:\n{}", wrong.len(), CASES.len(), wrong.join("\n"));
}
